// Downloads every product photo from sfs.com.lb, removes the white studio background
// (flood fill from the edges, soft edge), and writes public/products/<id>.webp + src/data/photos.ts.
// Usage: npm run fetch-images   (needs network access to sfs.com.lb)
import sharp from 'sharp';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(new URL('../src/data/products.ts', import.meta.url), 'utf8');
const UP = 'https://sfs.com.lb/wp-content/uploads/';
const items = [...src.matchAll(/id: '([^']+)'[\s\S]*?imageSrc: `\$\{UP\}([^`]+)`/g)].map(([, id, path]) => ({ id, url: UP + path }));

const TOL = 26; // how far from pure white still counts as background
const FEATHER = 18;

async function cutOut(buf) {
  const { data, info } = await sharp(buf).resize({ width: 900, withoutEnlargement: true }).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const { width: w, height: h } = info;
  const dist = (i) => 765 - (data[i] + data[i + 1] + data[i + 2]); // 0 = pure white
  const seen = new Uint8Array(w * h);
  const stack = [];
  for (let x = 0; x < w; x++) stack.push(x, (h - 1) * w + x);
  for (let y = 0; y < h; y++) stack.push(y * w, y * w + w - 1);
  while (stack.length) {
    const p = stack.pop();
    if (seen[p]) continue;
    const d = dist(p * 4);
    if (d > TOL + FEATHER) continue;
    seen[p] = 1;
    // soft edge: fully clear on white, partial alpha near the tolerance
    data[p * 4 + 3] = d <= TOL ? 0 : Math.round(((d - TOL) / FEATHER) * 255);
    if (d > TOL) continue;
    const x = p % w;
    if (x > 0) stack.push(p - 1);
    if (x < w - 1) stack.push(p + 1);
    if (p >= w) stack.push(p - w);
    if (p < w * (h - 1)) stack.push(p + w);
  }
  return sharp(data, { raw: { width: w, height: h, channels: 4 } }).trim({ threshold: 1 }).resize({ width: 600, height: 600, fit: 'inside' }).webp({ quality: 80, alphaQuality: 85, effort: 6 }).toBuffer();
}

mkdirSync(new URL('../public/products/', import.meta.url), { recursive: true });
const ok = [];
for (const { id, url } of items) {
  try {
    const res = await fetch(url, { headers: { 'User-Agent': 'Mozilla/5.0 (concept site image fetch)', Accept: 'image/webp,image/*' } });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const img = await cutOut(Buffer.from(await res.arrayBuffer()));
    writeFileSync(new URL(`../public/products/${id}.webp`, import.meta.url), img);
    ok.push(id);
    console.log(`✓ ${id}`);
  } catch (e) {
    console.log(`✗ ${id}: ${e.cause?.code ?? e.message}`);
  }
}
if (ok.length) {
  writeFileSync(
    new URL('../src/data/photos.ts', import.meta.url),
    `// Generated by scripts/fetch-images.mjs — ids that have a cut-out in public/products/<id>.webp.\nexport const PHOTOS: ReadonlySet<string> = new Set<string>(${JSON.stringify(ok)});\n`,
  );
}
console.log(`${ok.length}/${items.length} images ready. Check them visually before committing.`);
